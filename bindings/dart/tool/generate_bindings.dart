import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main(List<String> args) async {
  if (args.isNotEmpty && (args.length != 1 || args.single != '--check')) {
    throw ArgumentError(
      'Usage: dart run tool/generate_bindings.dart [--check]',
    );
  }
  final check = args.isNotEmpty;
  final packageRoot = Platform.script.resolve('../');
  final committed = File.fromUri(
    packageRoot.resolve('lib/src/bindings.g.dart'),
  );
  final generated = check
      ? File.fromUri(
          packageRoot.resolve('.dart_tool/mlsr-check/bindings.g.dart'),
        )
      : committed;
  await generated.parent.create(recursive: true);
  final libclangPath = Platform.environment['LIBCLANG_PATH'];

  await FfiGenerator(
    output: Output(
      dart: DartOutput(path: generated.uri),
      style: const NativeExternalBindings(
        assetId: 'package:mlsr/src/bindings.g.dart',
      ),
      preamble: '// Generated by ffigen. Do not edit by hand.',
    ),
    input: Input(
      entryPoints: [packageRoot.resolve('../../include/mlsr.h')],
      include: (header) => header.pathSegments.last == 'mlsr.h',
    ),
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = node.name.startsWith('mlsr_'),
        struct: (node) => node.isIncluded = node.name.startsWith('Mlsr'),
        macroConstant: (node) =>
            node.isIncluded = node.name.startsWith('MLSR_'),
      ),
    ],
  ).generate(
    libclangDylib: libclangPath == null ? null : File(libclangPath).uri,
  );

  if (check &&
      await generated.readAsString() != await committed.readAsString()) {
    stderr.writeln(
      'Dart bindings are stale; run python3 tools/dev.py generate.',
    );
    exitCode = 1;
  }
}
